"""OOSEM-ordered design documentation generated from the model. build(model, outdir, views_dir) -> markdown path."""
from __future__ import annotations
import os, datetime as dt
from . import derive as D

def tbl(headers, rows):
    L = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows: L.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |")
    return "\n".join(L)
def j(xs): return ", ".join(xs) if xs else "—"

def build(m, outdir, views_rel="../views", sysml_dir=None):
    os.makedirs(outdir, exist_ok=True)
    def fig(name, cap):
        return f"![{cap}]({views_rel}/{name}.png){{width=9.4in}}" if os.path.exists(os.path.join(outdir, views_rel, name + ".png")) else ""
    fm = D.fmea(m); vm = D.verification_matrix(m); cert = D.certification_plan(m); rep = D.coverage_report(m); c = rep["counts"]; dm = D.discipline_matrix(m)
    name = m["meta"].get("name", "System"); S = []
    S.append(f"""---
title: "{name} — System Design Documentation"
subtitle: "OOSEM digital thread · generated by sethread · reliability, safety and certification plans are derived"
date: "{dt.date.today():%B %d, %Y}"
---

Generated from a single system model. Every table carries the ids of the elements it was derived from; every figure is drawn from the same model. Trace check: **{'clean' if rep['clean'] else 'gaps open'}** — {len(rep['requirements_without_tests'])} requirements without tests, {len(rep['unassessed_candidates'])} unassessed failure-mode candidates, {len(rep['tests_unreferenced'])} unjustified tests.

{fig("V01_digital_thread", "Figure 1. The digital thread.")}

# Part A — Stakeholder needs (OOSEM 1)

{fig("V02_stakeholder_needs", "Figure 2. Stakeholders, needs and MoEs.")}

{tbl(["ID", "Stakeholder", "Role", "Concerns"], [(k, v["name"], v.get("role",""), v.get("concerns","")) for k, v in m["stakeholders"].items()])}

{tbl(["Need", "Stakeholder", "Statement", "MoE", "Target"], [(k, m["stakeholders"][v["stk"]]["name"], v["text"], m["moes"][v["moe"]]["name"], f'{m["moes"][v["moe"]]["target"]} {m["moes"][v["moe"]].get("unit","")}'.strip()) for k, v in m["needs"].items()])}

# Part B1 — System requirements (OOSEM 2)

{fig("V03_use_cases", "Figure 3. Use case view.")}

{tbl(["Use case", "Name", "Actors", "Includes", "Needs"], [(k, v["name"], j([m["actors"][a]["name"] for a in v["actors"]]), j([m["use_cases"][i]["name"] for i in v["includes"]]), j(v["needs"])) for k, v in m["use_cases"].items()])}

{tbl(["Scenario", "Use case", "Steps", "Concurrent"], [(k, m["use_cases"][v["uc"]]["name"], " → ".join(v["steps"]), j(v["concurrent"])) for k, v in m["scenarios"].items()])}

## Regulatory context

{tbl(["Regulation", "Market", "Applies because", "Standard(s)", "Requirements", "Tests"], [(r["name"], r["market"], r["trigger"], r["standard"], j(r["reqs"]), j(r["tests"])) for r in cert])}

## Requirements

{fig("V04_requirements", "Figure 4. Requirement view.")}

{tbl(["ID", "Type", "Requirement", "Derived from", "Verify", "Verified by", "Disciplines"], [(k, v["type"], v["text"], j(v["from_"] + v["regs"]), v["verify"], j(v["tests"]), j(dm[k])) for k, v in m["requirements"].items()])}

# Part B2 — Logical architecture (OOSEM 3)

{fig("V05_action_flows", "Figure 5. Action flows.")}

{tbl(["Function", "Name", "Realizes", "Logical component", "Allocated to", "Performance", "Safety decision"], [(k, v["name"], j(v["reqs"]), next((lc for lc, lv in m["logical_components"].items() if k in lv["funcs"]), "—"), j([m["parts"][p]["name"] for p in v["alloc"] if p in m["parts"]]), v.get("perf",""), v.get("safety_decision","")) for k, v in m["functions"].items()])}

{fig("V06_logical_architecture", "Figure 6. Logical architecture.")}

{tbl(["Logical component", "Role", "Functions", "Quality attributes", "Realized by"], [(f"{k} {v['name']}", v["role"], j(v["funcs"]), j(v.get("quality", [])), j([m["parts"][p]["name"] for p in v.get("parts", []) if p in m["parts"]])) for k, v in m["logical_components"].items()])}

{tbl(["Logical interface", "From", "To", "Flow"], [(k, m["logical_components"][v["a"]]["name"], m["logical_components"][v["b"]]["name"], v["flow"]) for k, v in m["logical_interfaces"].items()])}

# Part B3 — Physical architecture (OOSEM 4)

{tbl(["Decision", "Title", "Decision", "Rationale", "Trade", "Serves", "Consequences"], [(k, v["title"], v["decision"], v["rationale"], v.get("trade") or "—", j(v["reqs"]), "; ".join(v.get("consequences", []))) for k, v in m["arch_decisions"].items()])}

{fig("V07_physical_nodes", "Figure 7. Physical nodes.")}

{fig("V11_allocation", "Figure 8. Allocation.")}

{fig("V09_part_decomposition", "Figure 9. Part decomposition.")}

{tbl(["Part", "Name", "Type", "Discipline", "Parent", "Attributes"], [(k, v["name"], v["type"], v.get("discipline","system"), (m["parts"][v["parent"]]["name"] if v.get("parent") else "—"), "; ".join(f"{a}={b}" for a, b in v.get("attrs", {}).items()) or "—") for k, v in m["parts"].items()])}

{tbl(["Interface", "Name", "Items", "Type", "Functions"], [(k, v["name"], j(v["items"]), v["kind"], j(v["funcs"])) for k, v in m["interfaces"].items()])}

{fig("V10_states", "Figure 10. States.")}

{tbl(["Transition", "From", "To", "Trigger", "Guard", "Guard sensor", "Function"], [(k, m["states"][v["frm"]]["name"], m["states"][v["to"]]["name"], v["trigger"], v.get("guard") or "—", (m["parts"][v["sensor"]]["name"] if v.get("sensor") else "—"), v["func"]) for k, v in m["transitions"].items()])}

# Part B4 — Analysis and trades (OOSEM 5)

{fig("V12_analysis", "Figure 11. Constraints.")}

{tbl(["Constraint", "Name", "Formula", "Inputs", "Constrains", "Evaluated by"], [(k, v["name"], v["formula"], j(v.get("inputs", [])), j(v["reqs"]), j(v["tests"])) for k, v in m["constraints"].items()])}

{tbl(["Trade", "Question", "Options", "Criteria", "Recommendation", "Affects"], [(k, v["name"], " / ".join(v["options"]), j(v["criteria"]), v["recommendation"], j(v.get("affects", []))) for k, v in m["trades"].items()])}

# Part C — Verification and validation (OOSEM 6)

{tbl(["Test", "Name", "Method", "Gate", "Units", "Pass/fail", "Verifies", "Covers FMs", "Constraints", "Status"], [(t["id"], t["name"], t["method"], t["gate"], t.get("units",""), t["passfail"], j(t["reqs"]), j(t["fms"]), j(t["constraints"]), t.get("status", "")) for t in vm])}

{tbl(["Gate", "Date", "Exit criteria"], [(g, v["date"], v["exit"]) for g, v in m["gates"].items()])}

{fig("V14_roadmap", "Figure 12. Roadmap.")}

# Part D — Derived: reliability and risk

{fig("V13_fmea_coverage", "Figure 13. FMEA completeness map.")}

Candidates {c['candidates']}; assessed {c['assessed']} ({c['high_ap']} High AP, {c['safety_class']} safety-class); screened {c['screened']}; unassessed {len(rep['unassessed_candidates'])}.

{tbl(["FM", "AP", "Element", "Guide", "Failure mode", "Effect", "Cause", "S", "O", "D", "Controls", "Verified by", "Disciplines"], [(f["id"], f["AP"], f"{f['element']} {f['element_name'][:36]}", f["guide"], f["mode"], f["effect"], f["cause"], f["S"], f["O"], f["D"], f["controls"], j(f["tests"]), j(f["disciplines"])) for f in fm])}

## Screened candidates

{tbl(["Element", "Guide", "Reason"], [(f"{s['element']} {s['element_name'][:36]}", s["guide"], s["reason"]) for s in D.screened(m)])}

## Certification plan

{tbl(["Regulation", "Market", "Standard(s)", "Requirements", "Tests", "Parts in scope"], [(r["name"], r["market"], r["standard"], j(r["reqs"]), j(r["tests"]), j([m["parts"][p]["name"] for p in r["parts"] if p in m["parts"]])) for r in cert])}

# Part E — Trace

{tbl(["Check", "Result"], [(k, (len(v) if hasattr(v, "__len__") and not isinstance(v, dict) else v)) for k, v in rep.items() if k not in ("counts", "clean")])}

Trace edges: {len(D.trace(m))}.
""")
    md = "\n".join(S); path = os.path.join(outdir, "design_documentation.md"); open(path, "w").write(md); return path
